for (const [name,expected,source,consumer] of fixtures) test('native replacement effects: '+name,()=>{
  const report=new OsIndependenceChecker(new MemorySourceRepository([[file,source]]),{files:[file]}).check();
  assert.deepEqual(report.diagnostics.filter(entry=>entry.rule==='OS00'),[]);
  assert.equal(report.ok,expected,report.diagnostics.join('\n'));
  if(expected) { assert.equal(report.complete,true);assert.deepEqual(report.diagnostics,[]); }
  else assert.ok(consumer!==null&&report.diagnostics.some(entry=>entry.file===file&&entry.rule===consumer[0]
    &&entry.line===consumer[1]&&entry.column===consumer[2]&&entry.classification===consumer[3]),report.diagnostics.join('\n'));
});
