function fixture(t) {
  const root = createTmpDir("flow-process-handoff-");
  const owners = [];
  t.after(async () => {
    try { for (const owner of owners) await owner.close(); }
    finally { removeTmpDir(root); }
  });
  const source = path.join(root, ".sennel", "worktree", "feature-handoff");
  fs.mkdirSync(source, { recursive: true });
  const manager = makeFlowManager(root);
  const flow = new CanonicalFlowFixture({ flowManager: manager,
    execution: { mode: "worktree", baseBranch: "main", featureBranch: "feature/handoff" } }).create();
  const ctx = { root, mainRoot: root, executionRoot: source, flowManager: manager,
    flowState: flow.state(), specId: flow.specId };
  // The OS admission test injects an already acquired typed fact. It does not
  // claim that this fresh Draft fixture has produced Report or selected Sync.
  const authority = (context) => new FlowProcessPhysicalAuthority({ mainRoot: root, sourceRoot: source,
    executionRoot: root, contextRoot: context.executionRoot, runId: ctx.flowState.runId, specId: ctx.specId,
    selection: new FlowProcessExecutionBinding({ runId: ctx.flowState.runId, specId: ctx.specId, operation: "fixture-physical-handoff" }) });
  return { root, source, manager, flow, ctx, authority, owners };
}

function busy(error) { return error instanceof ProcessExecutionControlFailure && error.code === "PROCESS_EXECUTION_BUSY"; }

test("Flow admission seals the original checkout before real main docs and nested provider execution, retaining its reservation through removal", async (t) => {
  const value = fixture(t);
  const { root, source, ctx } = value;
  const before = value.manager.canonicalState(ctx.specId).toJSON();
  const generated = "Generated by the managed documentation provider.";
  const templates = path.join(root, ".sennel/templates/en/docs");
  fs.mkdirSync(templates, { recursive: true });
  fs.writeFileSync(path.join(root, ".sennel/config.json"), JSON.stringify({ type: "base", lang: "en",
    docs: { languages: ["en"], defaultLanguage: "en" },
    chapters: [{ chapter: "overview.md", desc: "Overview" }], scan: { include: ["input.txt"], exclude: [] },
    agent: { default: "fixture/exec", timeout: 20, retryCount: 1, providers: { "fixture/exec": {
      command: process.execPath, args: ["-e", `process.stdin.resume();process.stdout.write(${JSON.stringify(JSON.stringify({ overview: generated }))})`],
    } } } }));
  fs.writeFileSync(path.join(root, "input.txt"), "Documentation source.\n");
  fs.writeFileSync(path.join(templates, "overview.md"), ["# Overview", "", ...Array.from({ length: 20 }, (_, index) => `Documentation detail ${index}.`),
    '<!-- {{text({prompt: "Describe the source", id: "overview"})}} -->', '<!-- {{/text}} -->', ""].join("\n"));
  fs.writeFileSync(path.join(templates, "README.md"), "# Documentation\n");
  let original;
  let main;
  await withFlowProcessRuntime(ctx, async () => {
    original = ProcessExecutionRuntime.current();
    await runManagedCmdAsync(process.execPath, ["-e", "process.stdout.write('source')"], { cwd: source, timeout: 20000 });
    await withFlowProcessRuntime(ctx, async () => {
      main = ProcessExecutionRuntime.current();
      assert.equal(main.executionRoot, root);
      assert.equal(original.root.closed, true);
      const prior = ProcessExecutionRuntime.inspect({ mainRoot: root, executionRoot: source });
      assert.equal(prior.slot, null);
      assert.equal(prior.executions[0].calls[0].receipt.stopEvidence.status, "confirmed");
      await assert.rejects(ProcessExecutionRuntime.acquire({ mainRoot: root, executionRoot: source }), busy);
      await assert.rejects(ProcessExecutionRuntime.acquire({ mainRoot: root }), busy);
      const result = await new RunSyncCommand().execute({ ...ctx, dryRun: true });
      assert.equal(result.result, "dry-run");
      assert.match(fs.readFileSync(path.join(root, "docs/overview.md"), "utf8"), new RegExp(generated.replaceAll(".", "\\.")));
      const calls = main.inspect().executions.at(-1).calls;
      assert.ok(calls.some((call) => call.parentCallId !== null && call.invocation.kind === "provider"));
      assert.equal(calls.every((call) => call.receipt?.stopEvidence.status === "confirmed"), true);
      fs.rmSync(source, { recursive: true });
      assert.equal(fs.existsSync(source), false);
    }, { physicalAuthority: value.authority });
  });
  assert.equal(main.root.closed, true);
  assert.equal(ProcessExecutionRuntime.inspect({ mainRoot: root }).slot, null);
  assert.equal(fs.existsSync(original.store.ownerLock.lockPath), false);
  assert.deepEqual(value.manager.canonicalState(ctx.specId).toJSON(), before);
});

test("a main checkout contender refuses Flow handoff before effects and releases the sealed source reservation", async (t) => {
  const value = fixture(t);
  const before = value.manager.canonicalState(value.ctx.specId).toJSON();
  const mainOwner = await ProcessExecutionRuntime.acquire({ mainRoot: value.root });
  value.owners.push(mainOwner);
  let observed = false;
  await assert.rejects(withFlowProcessRuntime(value.ctx, async () => {
    await withFlowProcessRuntime(value.ctx, () => { observed = true; }, { physicalAuthority: value.authority });
  }), busy);
  assert.equal(observed, false);
  assert.deepEqual(value.manager.canonicalState(value.ctx.specId).toJSON(), before);
  const source = await ProcessExecutionRuntime.acquire({ mainRoot: value.root, executionRoot: value.source });
  await source.close();
});

